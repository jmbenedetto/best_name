def test_csv_results_structure():
    """Test that CSV results files have correct structure and columns."""
    try:
        import csv
        from datetime import datetime

        # Create a temporary results directory
        with tempfile.TemporaryDirectory() as temp_dir:
            results_dir = Path(temp_dir) / "test_results"
            results_dir.mkdir()

            csv_file = results_dir / "evaluation_results.csv"

            # Create CSV file as done in the implementation
            with open(csv_file, 'w', newline='', encoding='utf-8') as f:
                writer = csv.writer(f)
                writer.writerow([
                    'timestamp', 'original_filename', 'suggested_name',
                    'ground_truth_name', 'score', 'file_type', 'text_length', 'extractor'
                ])

                # Add sample data
                writer.writerow([
                    datetime.now().isoformat(),
                    'test_file.pdf',
                    'financial_report_2024',
                    'quarterly_report',
                    '8.5',
                    'pdf',
                    '1500',
                    'docling'
                ])

            # Verify file exists and has correct content
            assert csv_file.exists(), "CSV file should be created"

            # Read and verify structure
            with open(csv_file, 'r', encoding='utf-8') as f:
                reader = csv.reader(f)
                headers = next(reader)

                expected_headers = [
                    'timestamp', 'original_filename', 'suggested_name',
                    'ground_truth_name', 'score', 'file_type', 'text_length', 'extractor'
                ]

                assert headers == expected_headers, f"CSV headers mismatch: {headers} != {expected_headers}"

                # Verify data row
                data_row = next(reader)
                assert len(data_row) == 8, "CSV should have 8 columns"
                assert data_row[1] == 'test_file.pdf', "Original filename should be preserved"
                assert data_row[2] == 'financial_report_2024', "Suggested name should be recorded"
                assert data_row[4] == '8.5', "Score should be formatted as string"

        print("✓ CSV structure test passed")

    except ImportError as e:
        print(f"Skipping {test_csv_results_structure.__name__}: {e}")
