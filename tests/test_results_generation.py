def test_csv_timestamp_formatting():
    """Test that CSV timestamps are properly formatted as ISO strings."""
    try:
        import csv
        from datetime import datetime

        with tempfile.TemporaryDirectory() as temp_dir:
            results_dir = Path(temp_dir) / "test_results"
            results_dir.mkdir()

            csv_file = results_dir / "evaluation_results.csv"

            # Create CSV with timestamp
            test_timestamp = datetime.now().isoformat()

            with open(csv_file, 'w', newline='', encoding='utf-8') as f:
                writer = csv.writer(f)
                writer.writerow([
                    'timestamp', 'original_filename', 'suggested_name',
                    'ground_truth_name', 'score', 'file_type', 'text_length', 'extractor'
                ])
                writer.writerow([
                    test_timestamp,
                    'test.txt',
                    'suggested_name',
                    'ground_truth',
                    '7.5',
                    'txt',
                    '100',
                    'direct'
                ])

            # Read back and verify timestamp format
            with open(csv_file, 'r', encoding='utf-8') as f:
                reader = csv.reader(f)
                next(reader)  # Skip header
                row = next(reader)
                timestamp_str = row[0]

                # Verify ISO format (basic check for T and timezone/UTC pattern)
                assert 'T' in timestamp_str, f"Timestamp should contain 'T': {timestamp_str}"
                assert len(timestamp_str) >= 19, f"Timestamp should be complete: {timestamp_str}"

                # Try to parse as ISO format
                try:
                    from datetime import datetime
                    parsed = datetime.fromisoformat(timestamp_str.replace('Z', '+00:00'))
                    assert parsed is not None, "Timestamp should be parseable as ISO format"
                except ValueError as e:
                    raise AssertionError(f"Timestamp format is invalid ISO: {timestamp_str}, error: {e}")

        print("✓ CSV timestamp formatting test passed")

    except ImportError as e:
        print(f"Skipping {test_csv_timestamp_formatting.__name__}: {e}")
    except Exception as e:
        raise AssertionError(f"Test {test_csv_timestamp_formatting.__name__} failed: {e}")


